"use client";

import { useEffect, useState } from "react";
import { toast } from "sonner";

export const EmployeeDashboard = () => {
  const [user, setUser] = useState<any>(null);
  const [isLoading, setIsLoading] = useState(true);
  const [name, setName] = useState("");
  const [email, setEmail] = useState("");
  const [isUpdating, setIsUpdating] = useState(false);

  const fetchEmployeeData = async () => {
    setIsLoading(true);
    try {
      const res = await fetch("/api/employee/profile");
      if (res.ok) {
        const json = await res.json();
        setUser(json.data);
        setName(json.data.name);
        setEmail(json.data.email);
      } else {
        toast.error("Failed to load profile data.");
      }
    } catch (error) {
      toast.error("Network error.");
    } finally {
      setIsLoading(false);
    }
  };

  useEffect(() => {
    fetchEmployeeData();
  }, []);

  const handleUpdateProfile = async (e: React.FormEvent) => {
    e.preventDefault();
    setIsUpdating(true);

    try {
      const res = await fetch("/api/employee/profile", {
        method: "PATCH",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ name, email }),
      });

      if (res.ok) {
        toast.success("Profile updated successfully!");
        fetchEmployeeData();
      } else {
        const err = await res.json();
        toast.error(err.error || "Failed to update profile.");
      }
    } catch (error) {
      toast.error("Network error.");
    } finally {
      setIsUpdating(false);
    }
  };

  if (isLoading) return <div className="p-8 text-center text-gray-500">Loading dashboard...</div>;
  if (!user) return <div className="p-8 text-center text-red-500">Failed to load user info.</div>;

  return (
    <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
      {/* Profile & Editable Details */}
      <div className="p-6 bg-white rounded-lg shadow-sm border border-gray-200 space-y-4">
        <div>
          <h3 className="font-semibold text-gray-800 text-base">My Profile Status</h3>
          <span className={`inline-block mt-2 px-3 py-1 rounded-full text-xs font-semibold ${user.status === 'VERIFIED' ? 'bg-green-100 text-green-700' : 'bg-orange-100 text-orange-700'}`}>
            {user.status}
          </span>
        </div>

        <form onSubmit={handleUpdateProfile} className="space-y-3 pt-2 border-t">
          <h4 className="font-medium text-gray-700 text-sm">Edit Personal Details</h4>
          
          <div className="space-y-1">
            <label className="text-xs font-medium text-gray-500">Full Name</label>
            <input
              type="text"
              value={name}
              onChange={(e) => setName(e.target.value)}
              className="w-full px-3 py-1.5 border rounded-md text-sm"
              required
            />
          </div>

          <div className="space-y-1">
            <label className="text-xs font-medium text-gray-500">Email Address</label>
            <input
              type="email"
              value={email}
              onChange={(e) => setEmail(e.target.value)}
              className="w-full px-3 py-1.5 border rounded-md text-sm"
              required
            />
          </div>

          {/* Department & Designation managed by Admin */}
          <div className="grid grid-cols-2 gap-2 pt-2">
            <div className="p-2 bg-gray-50 rounded border text-xs">
              <span className="text-gray-400 block">Department</span>
              <span className="font-medium text-gray-700">{user.profile?.department || "N/A"}</span>
            </div>
            <div className="p-2 bg-gray-50 rounded border text-xs">
              <span className="text-gray-400 block">Designation</span>
              <span className="font-medium text-gray-700">{user.profile?.designation || "N/A"}</span>
            </div>
          </div>

          <button
            type="submit"
            disabled={isUpdating}
            className="w-full py-2 bg-blue-600 hover:bg-blue-700 text-white font-semibold rounded-md text-xs transition disabled:opacity-50"
          >
            {isUpdating ? "Saving..." : "Update Profile"}
          </button>
        </form>
      </div>

      {/* Salary Slips History */}
      <div className="p-6 bg-white rounded-lg shadow-sm border border-gray-200">
        <h3 className="font-semibold text-gray-800 text-base mb-4">My Salary Slips History</h3>
        
        {user.slips.length === 0 ? (
          <p className="text-sm text-gray-500 text-center py-8">No salary slips generated by admin yet.</p>
        ) : (
          <div className="overflow-x-auto border rounded-lg max-h-[350px] overflow-y-auto">
            <table className="w-full text-xs text-left">
              <thead className="bg-gray-50 border-b sticky top-0">
                <tr>
                  <th className="px-3 py-2 font-medium text-gray-900">Period</th>
                  <th className="px-3 py-2 font-medium text-gray-900">Net</th>
                  <th className="px-3 py-2 font-medium text-gray-900">Status</th>
                  <th className="px-3 py-2 font-medium text-gray-900 text-right">Action</th>
                </tr>
              </thead>
              <tbody className="divide-y">
                {user.slips.map((slip: any) => (
                  <tr key={slip.id} className="bg-white">
                    <td className="px-3 py-2.5 font-medium text-gray-900">
                      {slip.month} {slip.year}
                    </td>
                    <td className="px-3 py-2.5 font-bold text-blue-600">${slip.netAmount}</td>
                    <td className="px-3 py-2.5">
                      <span className="px-2 py-0.5 rounded-full text-[10px] font-semibold bg-green-50 text-green-700">
                        {slip.status}
                      </span>
                    </td>
                    <td className="px-3 py-2.5 text-right">
                      <button
                        onClick={() => alert(`Slip Details:\nPeriod: ${slip.month} ${slip.year}\nBasic: $${slip.basicSalary}\nBonus: $${slip.bonus}\nDeduction: $${slip.deduction}\nNet Payable: $${slip.netAmount}`)}
                        className="px-2 py-1 bg-gray-100 hover:bg-gray-200 text-gray-700 rounded text-[10px] font-medium transition"
                      >
                        View Slip
                      </button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </div>
  );
};